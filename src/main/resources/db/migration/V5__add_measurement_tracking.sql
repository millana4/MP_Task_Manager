-- Потоковый обход: отслеживание, когда карточку последний раз мерили
-- и когда последний раз ставили в очередь.
--
-- last_measured_at  — время последнего записанного замера. NULL = ещё ни разу.
--                     По нему выбираем «кого дольше всех не обходили» (сначала NULL).
-- last_enqueued_at  — время последней постановки в очередь обхода. Защита от
--                     повторной отправки карточки, по которой результат ещё не
--                     пришёл: планировщик тикает чаще, чем идёт обработка, и без
--                     этой метки одни и те же карточки слались бы каждый тик.
--                     Карточка снова становится кандидатом, если результат не
--                     пришёл за окно ожидания (inflight-timeout, по умолч. 15 мин)
--                     — это же и переотправляет реально потерянные задачи.
ALTER TABLE card ADD COLUMN last_measured_at TIMESTAMPTZ;
ALTER TABLE card ADD COLUMN last_enqueued_at TIMESTAMPTZ;

-- Индекс под выборку очереди: только активные, самые старые (и NULL) первыми.
CREATE INDEX idx_card_queue
    ON card (last_measured_at ASC NULLS FIRST)
    WHERE status = 'active';